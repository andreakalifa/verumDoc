"""
VD-C-007 — Schema riproducibile (REGOLE_SVILUPPO §16.2, §16.5, §16.6).

Su PostgreSQL REALE (server indicato da VD_TEST_DATABASE_URL, vedi
tests/infra_reale.py; l'utente deve poter creare database):
  1. database vuoto → `alembic upgrade head` (catena completa, nessun errore);
  2. `alembic check` in modalità confronto: nessuna differenza fra lo schema
     migrato e i modelli di libs/shared/models;
  3. ogni tipo enum PostgreSQL ha esattamente i valori dell'enum Python;
  4. seed eseguito due volte: idempotente, crea le classi di base e
     (in ENV test) il cliente dimostrativo, non tocca righe esistenti;
  5. `alembic downgrade base` e di nuovo `upgrade head`: la catena è
     reversibile e il risultato è ancora identico ai modelli.
Senza VD_TEST_DATABASE_URL i test si saltano con il motivo.
"""
from __future__ import annotations

import asyncio
import os
import uuid
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

import pytest

from tests.infra_reale import PG_TEMPLATE_URL, richiede_pg

GATEWAY = Path(__file__).resolve().parents[1]



def _url_db(nome: str) -> str:
    parti = urlsplit(PG_TEMPLATE_URL)
    return urlunsplit((parti.scheme, parti.netloc, f"/{nome}", parti.query, parti.fragment))


def _dsn(url: str) -> str:
    return url.replace("postgresql+asyncpg://", "postgresql://", 1)


async def _esegui(url: str, sql: str, *argomenti):
    import asyncpg

    conn = await asyncpg.connect(_dsn(url))
    try:
        return await conn.fetch(sql, *argomenti)
    finally:
        await conn.close()


@pytest.fixture
def db_vuoto(monkeypatch: pytest.MonkeyPatch):
    """Database nuovo e VUOTO (non dal template): la catena parte da zero."""
    nome = f"vds_{uuid.uuid4().hex[:12]}"
    admin = _url_db("postgres")
    asyncio.run(_esegui(admin, f'CREATE DATABASE "{nome}"'))
    url = _url_db(nome)
    monkeypatch.setenv("DATABASE_URL", url)  # env.py legge DATABASE_URL per primo
    try:
        yield url
    finally:
        asyncio.run(_esegui(admin, f'DROP DATABASE IF EXISTS "{nome}" WITH (FORCE)'))


def _config(confronto: bool = False):
    from alembic.config import Config

    cfg = Config(str(GATEWAY / "alembic.ini"))
    cfg.set_main_option("script_location", str(GATEWAY / "alembic"))
    if confronto:
        cfg.attributes["confronto_modelli"] = True
    return cfg


def _upgrade_e_check() -> None:
    from alembic import command

    command.upgrade(_config(), "head")
    # Solleva AutogenerateDiffsDetected se modelli e schema differiscono
    command.check(_config(confronto=True))


@richiede_pg
def test_db_vuoto_upgrade_head_uguale_ai_modelli(db_vuoto: str) -> None:
    _upgrade_e_check()
    righe = asyncio.run(_esegui(db_vuoto, "SELECT version_num FROM public.alembic_version"))
    from alembic.script import ScriptDirectory

    head = ScriptDirectory.from_config(_config()).get_current_head()
    assert [r["version_num"] for r in righe] == [head]


@richiede_pg
def test_enum_postgresql_uguali_agli_enum_python(db_vuoto: str) -> None:
    from alembic import command
    from sqlalchemy import Enum as SAEnum

    from libs.shared.models import Base

    command.upgrade(_config(), "head")
    righe = asyncio.run(_esegui(db_vuoto, """
        SELECT t.typname, array_agg(e.enumlabel ORDER BY e.enumsortorder) AS valori
        FROM pg_type t
        JOIN pg_enum e ON e.enumtypid = t.oid
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE n.nspname = 'public'
        GROUP BY t.typname
    """))
    nel_db = {r["typname"]: list(r["valori"]) for r in righe}
    nei_modelli = {}
    for tabella in Base.metadata.sorted_tables:
        for col in tabella.columns:
            if isinstance(col.type, SAEnum):
                nei_modelli[col.type.name] = list(col.type.enums)
    assert nel_db == nei_modelli


@richiede_pg
def test_seed_idempotente(db_vuoto: str) -> None:
    from alembic import command
    from app.seed import CLASSI_BASE, DEMO_TENANT_ID, run_seed

    command.upgrade(_config(), "head")
    dsn = _dsn(db_vuoto)
    primo = asyncio.run(run_seed(dsn=dsn, env="test"))
    # La migrazione 003 crea 8 classi di base; il seed aggiunge le mancanti
    assert primo["tenant_demo_creato"] is True
    codici = asyncio.run(_esegui(
        db_vuoto, "SELECT codice FROM public.classi_documentali WHERE tenant_id IS NULL",
    ))
    assert {r["codice"] for r in codici} == {c.codice for c in CLASSI_BASE}

    # Una modifica dell'utente non viene sovrascritta dal secondo lancio
    asyncio.run(_esegui(
        db_vuoto,
        "UPDATE public.classi_documentali SET anni_conservazione = 77 "
        "WHERE codice = 'fattura' AND tenant_id IS NULL",
    ))
    secondo = asyncio.run(run_seed(dsn=dsn, env="test"))
    assert secondo == {"classi_create": 0, "demo": True, "tenant_demo_creato": False}
    anni = asyncio.run(_esegui(
        db_vuoto, "SELECT anni_conservazione FROM public.classi_documentali "
                  "WHERE codice = 'fattura' AND tenant_id IS NULL",
    ))
    assert anni[0]["anni_conservazione"] == 77
    tenant = asyncio.run(_esegui(
        db_vuoto, "SELECT stato::text AS stato FROM public.tenants WHERE id = $1",
        uuid.UUID(DEMO_TENANT_ID),
    ))
    assert tenant[0]["stato"] == "TRIAL"


