@richiede_pg
def test_vincoli_reali_classi_e_nomine(db_vuoto: str) -> None:
    """Il database rifiuta davvero: codice di base duplicato, due nomine
    attive per lo stesso cliente; ammette la stessa classe in clienti diversi."""
    import asyncpg
    from alembic import command

    command.upgrade(_config(), "head")

    async def prova() -> None:
        conn = await asyncpg.connect(_dsn(db_vuoto))
        try:
            t1, t2 = uuid.uuid4(), uuid.uuid4()
            for t in (t1, t2):
                await conn.execute(
                    "INSERT INTO public.tenants (id, codice_fiscale, ragione_sociale, "
                    "schema_name, email_referente) VALUES ($1, $2, 'Prova', $3, 'p@example.org')",
                    t, t.hex[:16], f"t_{t.hex[:20]}",
                )
            with pytest.raises(asyncpg.UniqueViolationError):
                await conn.execute(
                    "INSERT INTO public.classi_documentali (codice, nome) VALUES ('fattura', "
                    "'Doppia')"
                )
            for t in (t1, t2):  # stessa classe in due clienti: ammessa
                await conn.execute(
                    "INSERT INTO public.classi_documentali (tenant_id, codice, nome) "
                    "VALUES ($1, 'fattura', 'Fattura del cliente')", t,
                )
            with pytest.raises(asyncpg.UniqueViolationError):
                await conn.execute(
                    "INSERT INTO public.classi_documentali (tenant_id, codice, nome) "
                    "VALUES ($1, 'fattura', 'Doppia')", t1,
                )
            nomina = (
                "INSERT INTO public.rsc_nominations (tenant_id, nome_rsc, codice_fiscale_rsc, "
                "email_rsc, data_nomina) VALUES ($1, 'Mario Rossi', 'FTZPRV00A01Z999V', "
                "'m@example.org', CURRENT_DATE)"
            )
            await conn.execute(nomina, t1)
            with pytest.raises(asyncpg.UniqueViolationError):
                await conn.execute(nomina, t1)
        finally:
            await conn.close()

    asyncio.run(prova())


def test_offline_sql_generabile() -> None:
    """`alembic upgrade head --sql` (revisione in finestra di manutenzione)
    produce lo script senza database."""
    import contextlib
    import io

    from alembic import command

    cfg = _config()
    buffer = io.StringIO()
    cfg.output_buffer = buffer
    vecchio = os.environ.get("DATABASE_URL")
    os.environ["DATABASE_URL"] = "postgresql+asyncpg://utente:segreto@localhost/nessuno"
    try:
        with contextlib.redirect_stdout(io.StringIO()):
            command.upgrade(cfg, "head", sql=True)
    finally:
        if vecchio is None:
            os.environ.pop("DATABASE_URL", None)
        else:
            os.environ["DATABASE_URL"] = vecchio
    script = buffer.getvalue()
    assert "CREATE TYPE public.modalita_formazione AS ENUM ('a', 'b', 'c', 'd')" in script
    assert "CREATE TABLE public.metadati_allegato5" in script
